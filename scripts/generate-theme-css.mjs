#!/usr/bin/env node
/**
 * generate-theme-css.mjs
 *
 * Builds the runtime theming layer from the Tokens Studio export:
 *
 *  1. Writes `styles/theme-tokens.css` — one CSS custom property per semantic
 *     theme token, with the Light value on `:root` and the Dark value under
 *     `[data-theme='dark']`. Toggling `data-theme` re-themes everything that
 *     reads these vars.
 *
 *  2. Rewrites `style-tokens.ts` so the flat `colors.semantic.theme.{semantic,
 *     text,background,border,icon}` leaves — and the duplicate `border.color.
 *     theme.*` leaves — become `var(--t-…, <lightHex>)` references instead of
 *     baked hex. Components that read these tokens then react to the theme with
 *     no per-component change. The light hex stays as a fallback so the tokens
 *     still render (in light) even without the CSS loaded.
 *
 * `colors.semantic.theme.light` / `.dark` keep their raw hex (they are the data
 * source for the CSS). `colors.primitive.*` stays raw hex (absolute values).
 *
 * Usage: node scripts/generate-theme-css.mjs [tokensDir] [styleTokensFile] [cssOut]
 */
import fs from 'node:fs'
import path from 'node:path'

const TOKENS_DIR = process.argv[2] ?? 'assets/token/tokens'
const STYLE_TOKENS = process.argv[3] ?? 'style-tokens.ts'
const CSS_OUT = process.argv[4] ?? 'styles/theme-tokens.css'

const readJSON = (p) => JSON.parse(fs.readFileSync(p, 'utf8'))
const prim = readJSON(path.join(TOKENS_DIR, 'Primitives/Value.json'))
const themeFiles = {
  light: readJSON(path.join(TOKENS_DIR, 'Theme/Light.json')),
  dark: readJSON(path.join(TOKENS_DIR, 'Theme/Dark.json')),
}

const isLeaf = (o) =>
  o && typeof o === 'object' && 'value' in o && 'type' in o && typeof o.value !== 'object'

function flatten(node, prefix, out) {
  if (!node || typeof node !== 'object') return out
  if (isLeaf(node)) {
    out[prefix] = node.value
    return out
  }
  for (const [k, v] of Object.entries(node)) flatten(v, prefix ? `${prefix}.${k}` : k, out)
  return out
}
function makeResolver(raw) {
  const res = (key, depth = 0) => {
    if (depth > 40) throw new Error(`alias cycle at ${key}`)
    const v = raw[key]
    if (v === undefined) throw new Error(`missing alias target: ${key}`)
    if (typeof v === 'string' && v.startsWith('{') && v.endsWith('}')) return res(v.slice(1, -1), depth + 1)
    return v
  }
  return res
}
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
function normHex(hex) {
  let h = String(hex).toLowerCase()
  if (/^#[0-9a-f]{6}$/.test(h)) h += 'ff'
  return h
}

// Resolve one mode into a nested camelCase dict of 8-digit hex.
function buildMode(theme) {
  const raw = {}
  flatten(prim, '', raw)
  flatten(theme, '', raw)
  const res = makeResolver(raw)
  const out = {}
  const walk = (node, trail) => {
    if (isLeaf(node)) {
      let cur = out
      for (let i = 0; i < trail.length - 1; i++) {
        const key = camel(trail[i])
        cur[key] = cur[key] ?? {}
        cur = cur[key]
      }
      cur[camel(trail.at(-1))] = normHex(res(trail.join('.')))
      return
    }
    for (const [k, v] of Object.entries(node)) walk(v, [...trail, k])
  }
  walk(theme, [])
  return out
}

const light = buildMode(themeFiles.light)
const dark = buildMode(themeFiles.dark)

const GROUP_ORDER = ['semantic', 'text', 'background', 'border', 'icon']

// Walk a mode dict collecting [varName, camelPath[], hex] for every leaf.
function collectVars(modeDict) {
  const rows = []
  const walk = (node, trail) => {
    if (typeof node === 'string') {
      const varName = '--t-' + trail.map(kebab).join('-')
      rows.push({ varName, trail: [...trail], hex: node })
      return
    }
    for (const [k, v] of Object.entries(node)) walk(v, [...trail, k])
  }
  walk(modeDict, [])
  return rows
}

const lightVars = collectVars(light)
const darkByName = new Map(collectVars(dark).map((r) => [r.varName, r.hex]))

// Collision guard
const seen = new Set()
for (const { varName } of lightVars) {
  if (seen.has(varName)) throw new Error(`duplicate CSS var name: ${varName}`)
  seen.add(varName)
}

// ── 1. Emit CSS ─────────────────────────────────────────────────────────────
function cssBlock(rows, getHex) {
  const byGroup = new Map()
  for (const r of rows) {
    const g = r.trail[0]
    if (!byGroup.has(g)) byGroup.set(g, [])
    byGroup.get(g).push(r)
  }
  const orderedGroups = [...GROUP_ORDER.filter((g) => byGroup.has(g)), ...[...byGroup.keys()].filter((g) => !GROUP_ORDER.includes(g))]
  const lines = []
  for (const g of orderedGroups) {
    lines.push(`  /* ${g} */`)
    for (const r of byGroup.get(g)) lines.push(`  ${r.varName}: ${getHex(r)};`)
  }
  return lines.join('\n')
}

const css = `/* AUTO-GENERATED by scripts/generate-theme-css.mjs — do not edit by hand.
 * Semantic theme tokens as CSS custom properties. Light on :root, Dark under
 * [data-theme='dark']. Source: assets/token (Tokens Studio export).
 */
:root {
${cssBlock(lightVars, (r) => r.hex)}
}

[data-theme='dark'] {
${cssBlock(lightVars, (r) => darkByName.get(r.varName) ?? r.hex)}
}
`
fs.mkdirSync(path.dirname(CSS_OUT), { recursive: true })
fs.writeFileSync(CSS_OUT, css)
console.log(`Wrote ${lightVars.length} CSS vars → ${CSS_OUT}`)

// ── 2. Build var() object (same structure as a mode, leaves = var refs) ──────
function varRefDict(modeDict, trail = []) {
  const out = {}
  for (const [k, v] of Object.entries(modeDict)) {
    if (typeof v === 'string') {
      const varName = '--t-' + [...trail, k].map(kebab).join('-')
      out[k] = `var(${varName}, ${v})`
    } else {
      out[k] = varRefDict(v, [...trail, k])
    }
  }
  return out
}
const varDict = varRefDict(light) // { semantic, text, background, border, icon }

function serialize(obj, indent) {
  const pad = ' '.repeat(indent)
  const padIn = ' '.repeat(indent + 2)
  const entries = Object.entries(obj)
  const lines = ['{']
  entries.forEach(([k, v], i) => {
    const comma = i < entries.length - 1 ? ',' : ''
    if (v && typeof v === 'object') lines.push(`${padIn}"${k}": ${serialize(v, indent + 2)}${comma}`)
    else lines.push(`${padIn}"${k}": "${v}"${comma}`)
  })
  lines.push(`${pad}}`)
  return lines.join('\n')
}

// ── 3. Patch style-tokens.ts ────────────────────────────────────────────────
const lines = fs.readFileSync(STYLE_TOKENS, 'utf8').split('\n')

function findFrom(re, start) {
  for (let i = start; i < lines.length; i++) if (re.test(lines[i])) return i
  return -1
}
function braceClose(openIdx) {
  let depth = 0
  for (let i = openIdx; i < lines.length; i++) {
    for (const ch of lines[i]) {
      if (ch === '{') depth++
      else if (ch === '}') depth--
    }
    if (depth === 0) return i
  }
  return -1
}

// (a) colors.semantic.theme flat groups: replace the contiguous run from the
//     first indent-6 "semantic": { up to (not incl.) the "light": { line.
const colorsThemeOpen = findFrom(/^ {4}"theme": \{/, 0)
const flatStart = findFrom(/^ {6}"semantic": \{/, colorsThemeOpen + 1)
const lightStart = findFrom(/^ {6}"light": \{/, colorsThemeOpen + 1)
if (colorsThemeOpen < 0 || flatStart < 0 || lightStart < 0) throw new Error('could not locate colors.semantic.theme flat groups')

const flatBlock = GROUP_ORDER.map((g) => `      "${g}": ${serialize(varDict[g], 6)}`).join(',\n') + ','

// (b) border.color.theme: replace inner content with the var() border group.
const borderExport = findFrom(/^export const border = \{/, 0)
const borderThemeOpen = findFrom(/^ {4}"theme": \{/, borderExport)
const borderThemeClose = braceClose(borderThemeOpen)
if (borderExport < 0 || borderThemeOpen < 0 || borderThemeClose < 0) throw new Error('could not locate border.color.theme')

// border.color.theme groups = the theme "border" group's subgroups (action/base/…)
const borderInner = Object.entries(varDict.border)
  .map(([g, obj], i, arr) => `      "${g}": ${serialize(obj, 6)}${i < arr.length - 1 ? ',' : ''}`)
  .join('\n')

// Apply patches bottom-up so indices stay valid.
lines.splice(borderThemeOpen + 1, borderThemeClose - borderThemeOpen - 1, borderInner)
lines.splice(flatStart, lightStart - flatStart, flatBlock)

fs.writeFileSync(STYLE_TOKENS, lines.join('\n'))
console.log(`Patched ${STYLE_TOKENS}: flat theme groups + border.color.theme → var() refs`)
